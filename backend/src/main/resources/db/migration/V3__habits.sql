-- M03 Habits (FR-03, FR-04, BR-6, BR-7, D-25)
CREATE TABLE habit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150)  NOT NULL,
    description VARCHAR(1000),
    frequency   VARCHAR(10)   NOT NULL,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_habit_frequency CHECK (frequency IN ('DAILY', 'WEEKLY'))
);

CREATE TABLE habit_completion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id        BIGINT NOT NULL,
    completion_date DATE   NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_habit_completion_habit FOREIGN KEY (habit_id) REFERENCES habit (id) ON DELETE CASCADE,
    CONSTRAINT uq_habit_completion UNIQUE (habit_id, completion_date)
);
