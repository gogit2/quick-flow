-- M04 Learning resources (FR-05, FR-06, BR-8, BR-9, D-30..D-32)
CREATE TABLE learning_card (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200)  NOT NULL,
    description VARCHAR(2000),
    status      VARCHAR(20)   NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_learning_card_status CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED'))
);

CREATE TABLE learning_milestone (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id      BIGINT       NOT NULL,
    title        VARCHAR(200) NOT NULL,
    done         BOOLEAN      NOT NULL DEFAULT FALSE,
    target_date  DATE,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    position     INT          NOT NULL,
    CONSTRAINT fk_learning_milestone_card FOREIGN KEY (card_id) REFERENCES learning_card (id) ON DELETE CASCADE
);

CREATE TABLE learning_note (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id    BIGINT        NOT NULL,
    text       VARCHAR(5000) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_learning_note_card FOREIGN KEY (card_id) REFERENCES learning_card (id) ON DELETE CASCADE
);

CREATE INDEX ix_learning_milestone_card ON learning_milestone (card_id);
CREATE INDEX ix_learning_note_card ON learning_note (card_id);
