-- M05 Todo plans (FR-07, FR-08, BR-10..BR-12, D-40..D-44)
CREATE TABLE plan (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(200) NOT NULL,
    estimated_duration  INT          NOT NULL,
    start_date_time     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    end_date_time       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    priority_order      INT          NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_plan_status CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'COMPLETED'))
);

CREATE TABLE plan_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id     BIGINT      NOT NULL,
    source_type VARCHAR(20) NOT NULL,
    source_id   BIGINT      NOT NULL,
    done        BOOLEAN     NOT NULL DEFAULT FALSE,
    position    INT         NOT NULL,
    CONSTRAINT fk_plan_item_plan FOREIGN KEY (plan_id) REFERENCES plan (id) ON DELETE CASCADE,
    CONSTRAINT uq_plan_item_source UNIQUE (plan_id, source_type, source_id),
    CONSTRAINT ck_plan_item_source_type CHECK (source_type IN ('TASK', 'HABIT', 'LEARNING_RESOURCE'))
);

CREATE INDEX ix_plan_item_plan ON plan_item (plan_id);
CREATE INDEX ix_plan_item_source ON plan_item (source_type, source_id);
